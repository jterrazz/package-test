/**
 * The signature cards — one generated page per KIND of test, under
 * `skills/jterrazz-test/references/`, plus the fork table those cards branch
 * from.
 *
 * A card is what an agent reads before writing a test of that kind: where the
 * file goes, the line that builds the runner, every constructor option with its
 * default, every setup, every terminal action, every result accessor, and the
 * chapter that explains them. It is a PROJECTION, never authored: the lists come
 * from the facet declaration (`facet-matrix.ts`), so a method added to a facet
 * and forgotten here fails a meta-test rather than going quietly missing from
 * the page an agent trusts.
 *
 * Two owners, and the boundary between them is the point:
 *
 * - `facet-matrix.ts` owns WHICH capabilities a column has. Nothing here may
 *   add a name it does not declare, and {@link SIGNATURES} must cover every one
 *   it does ({@link uncoveredCapabilities}, {@link deadSignatures}).
 * - this module owns how each one READS — its signature and its one line — once
 *   for the whole vocabulary, because `.seed()` means the same thing on four
 *   facets and a per-card description would be four chances to disagree.
 */

