/** The capabilities of one group that a column declares, in declaration order. */
function capabilitiesOf(kind: Kind, group: CapabilityGroup): string[] {
    return CAPABILITIES.filter(
        (capability) => capability.group === group && capability.columns.includes(kind),
    ).map((capability) => capability.name);
}

/** Every capability name the cards must describe. */
export function coveredGroups(): CapabilityGroup[] {
    return SECTIONS.map((section) => section.group);
}

/** Capability names of a rendered group that {@link SIGNATURES} does not describe. */
export function uncoveredCapabilities(): string[] {
    const groups = new Set<CapabilityGroup>(coveredGroups());
    return CAPABILITIES.filter(
        (capability) => groups.has(capability.group) && !(capability.name in SIGNATURES),
    ).map((capability) => capability.name);
}

/** Entries of {@link SIGNATURES} that no capability claims any more. */
export function deadSignatures(): string[] {
    const declared = new Set(CAPABILITIES.map((capability) => capability.name));
    return Object.keys(SIGNATURES).filter((name) => !declared.has(name));
}

/** A list of names as one line of inline code. */
function quoted(names: string[]): string {
    return names.map((name) => `\`${name}\``).join(' · ');
}

/** The element vocabulary a kind reaches, as two sentences — chapter 13 owns the words. */
function vocabulary(kind: Kind): string[] {
    const verbs = capabilitiesOf(kind, 'Verb');
    const descriptors = capabilitiesOf(kind, 'Descriptor');
    if (verbs.length === 0 && descriptors.length === 0) {
        return [];
    }
    return [
        '## The vocabulary',
        '',
        `The visitor's verbs: ${quoted(verbs)}.`,
        '',
        `The descriptors, landmarks and modifiers: ${quoted(descriptors)}.`,
        '',
        'All of them are defined once, in [13 — Elements](../../../docs/13-elements.md): the same words, the same W3 refusal, the same exact-by-default matching, on every surface that draws.',
    ];
}

/** One section of a card — a table of `signature | line`, or nothing if the kind has none. */
function sectionOf(kind: Kind, group: CapabilityGroup, title: string): string[] {
    const silent = HEADS[kind].silent?.[group];
    if (silent !== undefined) {
        return [`## ${title}`, '', `None here: ${silent}.`];
    }
    const names = capabilitiesOf(kind, group);
    if (names.length === 0) {
        return [];
    }
    const rows = names.map((name) => {
        const found = SIGNATURES[name];
        return [`\`${name}\``, cell(`\`${found?.signature ?? name}\``), cell(found?.line ?? '')];
    });
    return [`## ${title}`, '', ...table(['Name', 'Written', 'Does'], rows)];
}

/**
 * How a card shows the line a test opens on. A kind that STARTS something says
 * "constructed"; one that starts nothing says "written as", because there is no
 * runner to construct — and the kind that opens on nothing at all says so in a
 * sentence rather than in an empty fence.
 */
function constructed(head: CardHead): string {
    const label = head.started ? '**Constructed with**' : '**Written as**';
    if (!head.constructs.includes('\n')) {
        return `${label} — ${head.constructs}`;
    }
    return [label, '', '```typescript', head.constructs, '```'].join('\n');
}

/** One signature card — `skills/jterrazz-test/references/<kind>.md`. */
export function renderCard(kind: Kind): string {
    const head = HEADS[kind];
    const parts = [
        CARD_HEADER,
        `# \`@jterrazz/test\` — ${head.title}`,
        `> Generated from \`src/lint/cards.ts\` and the facet declaration by \`npm run docs\`. The chapter is [${head.chapter}](../../../docs/${head.chapter}).`,
        `**Specifies** — ${head.specifies}`,
        `**Lives at** — ${head.livesAt}`,
        `**Collected by** — \`${head.project}\` in \`vitest.config.ts\``,
        constructed(head),
        `**Not this kind** — ${head.refuses}`,
    ];
    for (const { group, title } of SECTIONS) {
        const body = sectionOf(kind, group, title);
        if (body.length > 0) {
            parts.push(body.join('\n'));
        }
    }
    const words = vocabulary(kind);
    if (words.length > 0) {
        parts.push(words.join('\n'));
    }
    parts.push(
        [
            '## Read next',
            '',
            `The chapter: [${head.chapter}](../../../docs/${head.chapter}). The fork: [fork.md](fork.md). What the package proves on each capability: [matrix.md](matrix.md). The rules that judge this file: [rules.md](rules.md).`,
        ].join('\n'),
    );
    return `${parts.join('\n\n')}\n`;
}

/** The fork table itself — the same rows in the chapter and in the card. */
function forkTable(): string[] {
    return table(
        ['Question', 'Kind', 'Lives at', 'Constructor', 'Project'],
        FORK.map((row) => [
            cell(row.question),
            row.kind,
            cell(row.livesAt),
            cell(row.constructor),
            cell(row.project),
        ]),
    );
}

/** Replace the region between the GENERATED markers of chapter 18 with a fresh fork table. */
export function spliceFork(existing: string): string {
    const start = existing.indexOf(FORK_START);
    const end = existing.indexOf(FORK_END);
    if (start === -1 || end === -1) {
        throw new Error(
            `docs/18-conventions.md is missing the GENERATED:fork markers (${FORK_START} … ${FORK_END})`,
        );
    }
    const inner = [FORK_START, '', ...forkTable(), '', FORK_END].join('\n');
    return existing.slice(0, start) + inner + existing.slice(end + FORK_END.length);
}

